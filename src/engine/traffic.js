import { clamp } from './math.js';

const WAVE_PERIOD_S = 30;
const WAVE_AMPLITUDE = 0.8;
const RAMP_PERIOD_S = 60;
const RAMP_GAIN = 5;
const MAX_SPIKE_FACTOR = 1000;

export function createSpike(factor, now, seconds) {
  return { factor: clamp(factor, 1, MAX_SPIKE_FACTOR), until: now + seconds };
}

/** Multiplier applied to every client's base load at simulated time `t`. */
export function trafficMultiplier(pattern, t, spike) {
  let multiplier = 1;
  if (pattern === 'wave') multiplier = 1 + WAVE_AMPLITUDE * Math.sin((t / WAVE_PERIOD_S) * 2 * Math.PI);
  else if (pattern === 'ramp') multiplier = 1 + RAMP_GAIN * ((t % RAMP_PERIOD_S) / RAMP_PERIOD_S);
  if (spike && t < spike.until) multiplier *= spike.factor;
  return multiplier;
}

/** Load offered to a node: generated by clients, otherwise whatever upstream nodes sent. */
export function offeredLoad(node, inflow, multiplier) {
  if (node.type !== 'client') return inflow;
  return node.up ? node.cfg.users * node.cfg.rpsPerUser * multiplier : 0;
}
